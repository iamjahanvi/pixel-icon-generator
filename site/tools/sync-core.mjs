// Copies the style checker and SVG writer from the skill's script into the site,
// so the site's editor applies exactly the same rules as the skill.
// Run from the repo root: node site/tools/sync-core.mjs
import fs from "node:fs";

const src = fs.readFileSync("skills/pixel-icons/scripts/pixelicon.mjs", "utf8");
const start = src.indexOf("export function check(");
const svgStart = src.indexOf("export function svg(");
const end = src.indexOf("\n}\n", svgStart) + 3;
if (start < 0 || svgStart < 0 || end < 3) throw new Error("could not find check() and svg() in pixelicon.mjs");
const out = `// Generated by site/tools/sync-core.mjs from skills/pixel-icons/scripts/pixelicon.mjs. Don't edit by hand.
export const N = 16;
const OUTLINE = "#000000";

${src.slice(start, end)}`;
fs.writeFileSync("site/js/core.js", out);
console.log("site/js/core.js updated");
