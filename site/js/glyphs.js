export function glyph(name, size = 32) {
  let d = "";
  G[name].forEach((row, y) => {
    for (let x = 0; x < 16;) {
      if (row[x] !== "#") { x++; continue; }
      let n = 1;
      while (row[x + n] === "#") n++;
      d += `M${x} ${y}h${n}v1h-${n}z`;
      x += n;
    }
  });
  return `<svg width="${size}" height="${size}" viewBox="0 0 16 16" aria-hidden="true" shape-rendering="crispEdges"><path fill="currentColor" d="${d}"/></svg>`;
}
